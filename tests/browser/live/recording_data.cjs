/* Recording boundaries, units, missing IMU and raw waveform preservation. */
const assert=require('node:assert/strict'),vm=require('node:vm');
const {runWebScript}=require('../web_files.cjs');
const window={};runWebScript('recording-data.js',vm.createContext({window,console,Date}));
const {Capture}=window.RecordingData;
const imu={sequence:1,received_ms:1000050,attitude:[30,5,-2],magnetic:[.1,.2,.3],acceleration:[0,0,-9.8],angular_rate:[.01,.02,.03]};
const ap=new Capture('ap230',{now:1000000});
ap.receiveIMU({session:'a',status:'live',samples:[imu]});
ap.receive({ap:{status:'live',stream_id:1,count:10,samples_start_count:10,samples:[[999.9,1,2,3,4]]}});
const message={ap:{status:'live',stream_id:1,count:12,samples_start_count:11,samples:[[1000.05,3,4,12,13],[1001,5,6,7,8]]}};
ap.receive(message);ap.receive(message);
const apDocument=ap.document();
assert.equal(apDocument.samples.length,2,'No historical rows or duplicate polls');
assert.equal(apDocument.samples[0].magnetic_z_uT,12,'uT must remain uT');
assert.equal(apDocument.samples[0].yaw_deg,30,'Nearest IMU joins the row');
assert.equal(apDocument.samples[0].imu_time_offset_ms,0);
assert.equal(apDocument.samples[1].yaw_deg,null,'Stale IMU must remain missing');
assert.equal(apDocument.imu_samples[0].angular_rate[2],.03,'All IMU groups retained');
ap.receive({ap:{...message.ap,stream_id:2}});
assert.match(ap.reason,/restarted/,'Do not mix acquisition epochs');
const mc=new Capture('mc95a',{now:1000000,settings:{gain:k=>k===0?10:1,sensitivity:()=>2}});
const channel=(k)=>({channel:k,label:`S${k+1}`,board_address:0,board_channel:k,
  latest:{t:5,duration_s:.1,ac_rms_V:.02,band_rms_V:.004,waveform_V:[-.1,.2]},spectrum:{peak_Hz:200}});
const em={status:'live',stream_id:3,sequence:1,age_s:0,sample_rate_Hz:20,channels:[channel(0),channel(1)]};
mc.receive({mc:em},1000000);mc.receiveIMU({session:'a',status:'live',samples:[{...imu,received_ms:1000200}]});
mc.receive({mc:{...em,sequence:3}},1000200);
const mcDocument=mc.document(),row=mcDocument.samples[0];
assert.equal(row.mc95a_s1_ac_rms_V,.002,'External gain applied once');
assert.equal(row.mc95a_s1_field_rms_nT,20,'0.004 V / 10 gain * 100000 nT/V / 2 sensitivity');
assert.equal(mcDocument.waveforms[0].channels[0].adc_V[1],.2,'Raw ADC values unmodified');
assert.equal(mcDocument.metadata.missing_blocks,1,'Missing ADC blocks must be reported');
assert.equal(row.yaw_deg,30);assert.equal(row.time,5,'ADC elapsed time is not Unix time');
assert.equal(Object.keys(row).some(k=>/Bx_re|Bx_im/.test(k)),false,'No fabricated phasor');
const bounded=new Capture('ap230',{limit:1});
bounded.receive({ap:{...message.ap,count:10}});bounded.receive(message);
assert.equal(bounded.full,true);assert.equal(bounded.samples.length,0);
assert.equal(bounded.append(bounded.samples,{}),false,'Stop all buffers at the size bound');
module.exports={ap:apDocument,mc:mcDocument};
if(require.main===module)console.log('PASS: recording boundaries, units, IMU association, waveform fidelity and gaps');
